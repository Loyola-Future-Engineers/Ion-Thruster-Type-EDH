BOOKS = """
@book{peek1929,
  author = {Peek, F. W.},
  title = {Dielectric Phenomena in High-Voltage Engineering},
  edition = {3rd}, publisher = {McGraw-Hill}, year = {1929}}

@book{idelchik,
  author = {Idelchik, I. E.},
  title = {Handbook of Hydraulic Resistance},
  publisher = {Begell House},
  note = {General source of screen/obstruction loss correlations. The simplified coefficients in src/ehd/device.py are assumptions, not values transcribed from it.}}
"""


def fetch(doi):
    req = urllib.request.Request(f"https://api.crossref.org/works/{doi}",
                                 headers={"User-Agent": "ehd-research (mailto:none@example.org)"})
    return json.load(urllib.request.urlopen(req, timeout=30))["message"]


def main():
    print("% Generated by references/build_bib.py from Crossref metadata.\n")
    for key, doi in DOIS.items():
        m = fetch(doi)
        authors = " and ".join(f"{a.get('family', '')}, {a.get('given', '')}".strip(", ")
                               for a in m.get("author", []))
        title = re.sub(r"<[^>]+>", "", m["title"][0]).strip()
        venue = (m.get("container-title") or [""])[0]
        year = m.get("issued", {}).get("date-parts", [[None]])[0][0]
        kind = "inproceedings" if m.get("type") == "proceedings-article" else "article"
        field = "booktitle" if kind == "inproceedings" else "journal"
        extra = "".join(f",\n  {k} = {{{m[k]}}}" for k in ("volume", "page") if m.get(k))
        print(f"@{kind}{{{key},\n  author = {{{authors}}},\n  title = {{{title}}},\n"
              f"  {field} = {{{venue}}},\n  year = {{{year}}}{extra},\n  doi = {{{m['DOI']}}}}}\n")
    print(BOOKS)


if __name__ == "__main__":
    main()
